// Generate the Worker-loadable module from the reviewed permissions.json manifest.
// Run from any directory: node cloudflare-worker/scripts/generate-permissions.mjs
import { readFile, writeFile } from 'node:fs/promises';
const source = new URL('../permissions.json', import.meta.url);
const target = new URL('../permissions-module.js', import.meta.url);
const policy = JSON.parse(await readFile(source, 'utf8'));
if (policy.defaultDecision !== 'deny' || policy.serverCapabilities?.['execution.shell'] !== false) {
  throw new Error('Unsafe permission manifest: deny-by-default baseline is required');
}
const moduleSource = '// GENERATED from permissions.json. Do not edit this file by hand.\n'
  + '// Regenerate when changing the version-controlled permission manifest.\n'
  + 'export default ' + JSON.stringify(policy, null, 2) + ';\n';
await writeFile(target, moduleSource, 'utf8');
console.log('Generated permissions-module.js from permissions.json');
