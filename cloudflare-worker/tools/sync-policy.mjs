#!/usr/bin/env node
// Source of truth: cloudflare-worker/permissions.json -> generated ESM module.
// Owner's system prompt stays in policy/system_prompt.md -> worker.js.
// This validator NEVER replaces the module import with a hard-coded policy copy.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..','..');
const app=path.join(root,'cloudflare-worker');
const mainPath=path.join(app,'worker.js');
const manifestPath=path.join(app,'permissions.json');
const modulePath=path.join(app,'permissions-module.js');
const promptPath=path.join(root,'policy','system_prompt.md');
const policy=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
if(policy.defaultDecision!=='deny'||policy.serverCapabilities?.['execution.shell']!==false||policy.serverCapabilities?.['deployment.self_modify']!==false){
 throw new Error('Unsafe policy manifest: deny-by-default baseline is required');
}
const moduleExpected='// GENERATED from permissions.json. Do not edit this file by hand.\n'
 +'// Regenerate when changing the version-controlled permission manifest.\n'
 +'export default '+JSON.stringify(policy,null,2)+';\n';
const workerSource=fs.readFileSync(mainPath,'utf8');
const prompt=fs.readFileSync(promptPath,'utf8').trim();
const policyImport="import LAB_POLICY_MANIFEST from './permissions-module.js';";
const policyBinding='const LAB_POLICY = Object.freeze(LAB_POLICY_MANIFEST);';
if(!workerSource.includes(policyImport)||!workerSource.includes(policyBinding)){
 throw new Error('Worker must import and freeze the version-controlled policy module');
}
const current=fs.readFileSync(modulePath,'utf8');
const start=workerSource.indexOf('const LAB_BASE_INSTRUCTIONS = ');
const nextDeclaration=workerSource.indexOf('function capabilityEnabled',start);
const end=nextDeclaration<0?-1:workerSource.lastIndexOf(';',nextDeclaration);
if(start<0||end<0)throw new Error('Worker prompt markers missing');
const actualPrompt=JSON.parse(workerSource.slice(start+'const LAB_BASE_INSTRUCTIONS = '.length,end));
const check=process.argv.includes('--check');
if(check){
 if(current.replace(/\r\n/g,'\n')!==moduleExpected||actualPrompt!==prompt){
  console.error('Wormstar policy module or system prompt out of sync. Run: node cloudflare-worker/tools/sync-policy.mjs');
  process.exitCode=1;
 }else console.log('Wormstar policy module and system prompt are synchronized.');
}else{
 if(current.replace(/\r\n/g,'\n')!==moduleExpected)fs.writeFileSync(modulePath,moduleExpected);
 if(actualPrompt!==prompt)fs.writeFileSync(mainPath,workerSource.slice(0,start)+'const LAB_BASE_INSTRUCTIONS = '+JSON.stringify(prompt)+workerSource.slice(end));
 console.log('Synchronized Wormstar permissions module and system prompt.');
}

